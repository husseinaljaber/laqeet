  function iconHtml(name, cls) {
    const inner = PATHS[name] || PATHS.sparkles;
    return `<svg class="ico${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
  }

  function icon(name, cls) {
    const span = document.createElement('span');
    span.className = 'ico-wrap' + (cls ? ' ' + cls : '');
    span.setAttribute('aria-hidden', 'true');
    span.innerHTML = iconHtml(name);
    return span;
  }

  function hydrateIcons(root) {
    (root || document).querySelectorAll('[data-ico]').forEach((node) => {
      const name = node.getAttribute('data-ico');
      const extraCls = node.getAttribute('data-ico-cls') || '';
      node.innerHTML = iconHtml(name, extraCls);
      node.classList.add('ico-wrap');
      node.setAttribute('aria-hidden', 'true');
      node.removeAttribute('data-ico');
    });
  }

  function syncThemeButtons() {
    const dark = getPreferredDark();
    document.querySelectorAll('[data-theme-toggle]').forEach((btn) => {
      const icoSlot = btn.querySelector('.theme-ico');
      const lblSlot = btn.querySelector('.theme-lbl');
      if (icoSlot) icoSlot.innerHTML = iconHtml(dark ? 'sun' : 'moon');
      if (lblSlot) lblSlot.textContent = dark ? 'النهاري' : 'الليلي';
      btn.setAttribute('aria-label', dark ? 'التبديل إلى الوضع النهاري' : 'التبديل إلى الوضع الليلي');
      btn.setAttribute('aria-pressed', String(dark));
    });
  }

  function toggleTheme() {
    const next = getPreferredDark() ? 'light' : 'dark';
    document.documentElement.dataset.theme = next;
    try { localStorage.setItem(THEME_KEY, next); } catch (_) {}
    syncThemeButtons();
  }

  function initSharedChrome() {
    hydrateIcons(document);
    syncThemeButtons();

    document.querySelectorAll('[data-theme-toggle]').forEach((btn) => {
      btn.addEventListener('click', toggleTheme);
    });

    const nav = document.querySelector('.site-nav');
    if (nav) {
      const onScroll = () => nav.classList.toggle('is-scrolled', window.scrollY > 10);
      onScroll();
      window.addEventListener('scroll', onScroll, { passive: true });

      const menuBtn = nav.querySelector('[data-nav-menu-toggle]');
      const linksBox = nav.querySelector('.site-nav-links');
      if (menuBtn && linksBox) {
        menuBtn.addEventListener('click', () => {
          const open = linksBox.classList.toggle('open');
          menuBtn.setAttribute('aria-expanded', String(open));
          menuBtn.innerHTML = iconHtml(open ? 'x' : 'menu');
        });
        linksBox.addEventListener('click', (e) => {
          if (e.target.closest('a, button')) {
            linksBox.classList.remove('open');
            menuBtn.setAttribute('aria-expanded', 'false');
            menuBtn.innerHTML = iconHtml('menu');
          }
        });
      }
    }
  }

  // Anonymous usage counters: one number goes up on the server. No cookie, no id, nothing about the person.
  function track(event, key, source) {
    try {
      if (navigator.doNotTrack === '1' || window.doNotTrack === '1') return;
      const body = JSON.stringify({ e: event, k: key || '', s: source || '' });
      if (navigator.sendBeacon) navigator.sendBeacon('/api/e', new Blob([body], { type: 'application/json' }));
      else fetch('/api/e', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body, keepalive: true }).catch(() => {});
    } catch (_) {}
  }
  const PAGE_VIEWS = { 'cv.html': 'cv', 'pulse.html': 'pulse', 'scam.html': 'scam', 'employer.html': 'employer' };
  const pageName = PAGE_VIEWS[(location.pathname.split('/').pop() || '')];
  if (pageName) track('view', pageName);

